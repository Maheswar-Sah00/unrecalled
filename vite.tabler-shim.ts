// Dev-only fix for slow page loads.
//
// Every import in the app and in @agent-native/* uses the "@tabler/icons-react"
// barrel. In `vite dev` that barrel is pre-bundled whole: ~6,000 icons, 4.2 MB
// that the browser parses and runs on every load (~470 ms vs ~15 ms for the
// subset, measured in headless Chromium). Production builds tree-shake it, so
// this only matters in dev.
//
// At dev-server start we scan the app and the framework for the icon names they
// actually import, write a tiny module that re-exports just those, and alias the
// bare "@tabler/icons-react" specifier to it. Adding a new icon? Restart dev.
import fs from "node:fs";
import path from "node:path";
import type { Alias } from "vite";

const PKG = "@tabler/icons-react";
const IMPORT_RE =
  /(?:import|export)\s*(type\s*)?\{([^}]*)\}\s*from\s*["']@tabler\/icons-react["']/g;

function walk(dir: string, out: string[]) {
  let entries: fs.Dirent[];
  try {
    entries = fs.readdirSync(dir, { withFileTypes: true });
  } catch {
    return;
  }
  for (const e of entries) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) {
      if (e.name !== "node_modules" && e.name !== "tabler-chunks") walk(p, out);
    } else if (/\.(m?js|tsx?|jsx)$/.test(e.name) && !e.name.endsWith(".d.ts")) {
      out.push(p);
    }
  }
}

export function tablerDevAlias(root: string): Alias[] {
  try {
    const tablerDir = fs.realpathSync(path.join(root, "node_modules", PKG));
    const esm = path.join(tablerDir, "dist/esm");

    // Map every exported name in the barrel to the file that defines it
    // (the barrel also re-exports aliases, e.g. old names for renamed icons).
    const barrel = fs.readFileSync(path.join(esm, "tabler-icons-react.mjs"), "utf8");
    const fileFor = new Map<string, string>();
    for (const m of barrel.matchAll(/export\s*\{([^}]*)\}\s*from\s*'([^']+)'/g)) {
      const [, list = "", file] = m;
      if (!file) continue;
      for (const part of list.split(",")) {
        const [orig, alias] = part.trim().split(/\s+as\s+/);
        if (orig) fileFor.set((alias ?? orig).trim(), file);
      }
    }

    const files: string[] = [];
    walk(path.join(root, "app"), files);
    for (const pkg of ["core", "toolkit", "agentkit"]) {
      try {
        walk(path.join(fs.realpathSync(path.join(root, "node_modules/@agent-native", pkg)), "dist"), files);
      } catch {
        /* package not installed */
      }
    }

    const names = new Set<string>(["createReactComponent"]);
    for (const f of files) {
      const src = fs.readFileSync(f, "utf8");
      if (!src.includes(PKG)) continue;
      for (const m of src.matchAll(IMPORT_RE)) {
        if (m[1]) continue; // `import type { ... }`
        for (const part of (m[2] ?? "").split(",")) {
          const name = (part.trim().split(/\s+as\s+/)[0] ?? "").trim();
          if (name && !name.startsWith("type ") && fileFor.has(name)) names.add(name);
        }
      }
    }

    const lines = [...names].sort().map((n) => {
      const rel = fileFor.get(n)!.replace(/^\.\//, "");
      return `export { default as ${n} } from "${PKG}/dist/esm/${rel}";`;
    });
    const shim = path.join(root, ".generated", "tabler-icons-dev.mjs");
    fs.mkdirSync(path.dirname(shim), { recursive: true });
    const content = `// Generated by vite.tabler-shim.ts. Do not edit.\n${lines.join("\n")}\n`;
    if (!fs.existsSync(shim) || fs.readFileSync(shim, "utf8") !== content) {
      fs.writeFileSync(shim, content);
    }
    return [{ find: /^@tabler\/icons-react$/, replacement: shim }];
  } catch (err) {
    console.warn("[unrecalled] tabler dev shim skipped:", err);
    return [];
  }
}
